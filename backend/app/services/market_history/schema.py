def ohlcv_table_sql(name: str = STAGING_OHLCV_TABLE) -> tuple[str, ...]:
    """Tabela de candles com chave ``(series_id, candle_time)``.

    ``symbol``, ``timeframe`` e ``source`` ficam só para leitura de compatibilidade
    (indicadores e consultas antigas) até o #1126.
    """

    return (
        f"""
        CREATE TABLE IF NOT EXISTS {name} (
            series_id INTEGER NOT NULL,
            candle_time TIMESTAMPTZ NOT NULL,
            open NUMERIC NOT NULL,
            high NUMERIC NOT NULL,
            low NUMERIC NOT NULL,
            close NUMERIC NOT NULL,
            volume NUMERIC NOT NULL,
            symbol TEXT NOT NULL,
            timeframe TEXT NOT NULL,
            source TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
            CONSTRAINT {name}_pkey PRIMARY KEY (series_id, candle_time)
        )
        """,
        f"""
        CREATE INDEX IF NOT EXISTS idx_{name}_symbol_timeframe_time
        ON {name} (symbol, timeframe, candle_time DESC)
        """,
    )


