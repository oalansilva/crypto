def execute_all(conn, statements: Iterable[str]) -> None:
    for statement in statements:
        conn.execute(text(statement))


def has_column(conn, table: str, column: str) -> bool:
    return bool(
        conn.execute(
            text(
                "SELECT 1 FROM information_schema.columns "
                "WHERE table_schema = current_schema() "
                "AND table_name = :t AND column_name = :c"
            ),
            {"t": table, "c": column},
        ).scalar()
    )


def has_table(conn, table: str) -> bool:
    return bool(
        conn.execute(
            text(
                "SELECT 1 FROM information_schema.tables "
                "WHERE table_schema = current_schema() AND table_name = :t"
            ),
            {"t": table},
        ).scalar()
    )


def timescale_available(conn) -> bool:
    return bool(
        conn.execute(text("SELECT 1 FROM pg_extension WHERE extname = 'timescaledb'")).scalar()
    )


def ohlcv_table_is_new_shape(conn, table: str = LIVE_OHLCV_TABLE) -> bool:
    return has_table(conn, table) and has_column(conn, table, "series_id")


def resolve_ohlcv_table(conn) -> str | None:
    """Nome da tabela de candles em uso: a nova (depois da troca) ou a de preparo."""

    if ohlcv_table_is_new_shape(conn, LIVE_OHLCV_TABLE):
        return LIVE_OHLCV_TABLE
    if has_table(conn, STAGING_OHLCV_TABLE):
        return STAGING_OHLCV_TABLE
    return None


def configure_timescale(conn, table: str) -> dict[str, bool]:
    """Hypertable + compressão aos 30 dias; nunca retenção (spec ``ohlcv-storage``).

    Sem a extensão (DEV hoje), a tabela fica comum e o resultado diz por quê.
    """

    result = {"timescale": False, "hypertable": False, "compression": False}
    if not timescale_available(conn):
        return result
    result["timescale"] = True
    nested = conn.begin_nested()
    try:
        conn.execute(
            text(
                f"SELECT create_hypertable('{table}', 'candle_time', "
                "if_not_exists => TRUE, migrate_data => TRUE)"
            )
        )
        nested.commit()
        result["hypertable"] = True
    except Exception:
        nested.rollback()
        return result
    nested = conn.begin_nested()
    try:
        conn.execute(
            text(
                f"ALTER TABLE {table} SET (timescaledb.compress, "
                "timescaledb.compress_orderby = 'candle_time DESC', "
                "timescaledb.compress_segmentby = 'series_id')"
            )
        )
        conn.execute(
            text(
                f"SELECT add_compression_policy('{table}', INTERVAL '30 days', if_not_exists => TRUE)"
            )
        )
        nested.commit()
        result["compression"] = True
    except Exception:
        nested.rollback()
    return result


def remove_retention_policy(conn, table: str = LIVE_OHLCV_TABLE) -> bool:
    """Tira a política de retenção de 2 anos, se existir (tarefa 1.3)."""

    if not timescale_available(conn) or not has_table(conn, table):
        return False
    nested = conn.begin_nested()
    try:
        conn.execute(text(f"SELECT remove_retention_policy('{table}', if_exists => TRUE)"))
        nested.commit()
        return True
    except Exception:
        nested.rollback()
        return False
